"""Renders eval/report.md from the measured results (no numbers are typed by hand)."""
from __future__ import annotations

from .dataset import CATEGORIES
from .metrics import METRIC_NAMES

MODE_LABEL = {"bm25": "BM25", "dense": "Dense (MiniLM + exact cosine)", "hybrid": "Hybrid RRF",
              "hybrid_rerank": "Hybrid RRF + cross-encoder"}
HEADLINE = ["recall@1", "recall@5", "recall@10", "mrr@10", "ndcg@5", "hit@5"]
COLD_ORDER = ["load_corpus_from_sqlite", "load_bm25_index", "load_faiss_index",
              "load_embedding_model_and_first_encode", "load_cross_encoder_and_first_score"]
STAGE_ORDER = ["bm25_search (pool 30)", "dense_query_embedding",
               "dense_search incl. embedding (pool 30)", "rrf_fusion",
               "cross_encoder_rerank (30 candidates)"]
FIELD = {"recall@1": "Recall@1", "recall@5": "Recall@5", "recall@10": "Recall@10",
         "mrr@10": "MRR@10", "ndcg@5": "nDCG@5", "hit@5": "Hit@5"}


def _f(x, nd=3):
    return "-" if x is None else f"{x:.{nd}f}"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out + [""]


def _rank(e: dict, mode: str) -> str:
    r = e[mode]["first_relevant_rank"]
    return "miss" if r is None else str(r)


def _examples(title: str, items: list[dict], limit: int = 8) -> list[str]:
    out = [f"**{title}** ({len(items)} queries" + (f", first {limit} by query ID shown" if len(items) > limit
                                                       else "") + ")", ""]
    if not items:
        return out + ["_none_", ""]
    rows = [[e["query_id"], e["question"][:70], _rank(e, "bm25"), _rank(e, "dense"),
             _rank(e, "hybrid"), _rank(e, "hybrid_rerank"),
             _f(e["bm25"]["ndcg@5"], 2), _f(e["dense"]["ndcg@5"], 2),
             _f(e["hybrid"]["ndcg@5"], 2), _f(e["hybrid_rerank"]["ndcg@5"], 2)]
            for e in items[:limit]]
    return out + _table(["Query", "Question", "BM25 rank", "Dense rank", "Hybrid rank",
                         "Rerank rank", "BM25 nDCG", "Dense nDCG", "Hybrid nDCG", "Rerank nDCG"],
                        rows)


def render_report(res: dict) -> str:
    meta, modes = res["meta"], res["modes"]
    names = [m for m in MODE_LABEL if m in modes]
    ds = meta["dataset"]
    L: list[str] = ["# ControlShift retrieval benchmark", "",
                    "_Generated by `eval/benchmark.py` from `eval/results.json`; every number below is "
                    "measured. Labels are AI-curated and source-checked, **not human-reviewed**._", ""]
    L += ["## 1. Methodology", "",
          f"- Corpus: {meta['corpus']['n_chunks']} source chunks from NIST CSF 1.1 and 2.0 "
          f"({meta['corpus']['n_passages']} dense embedding passages; passages are scored as their "
          "parent chunk).",
          f"- Questions: {ds['n_total']} ({ds['n_final']} final, {ds['n_provisional']} provisional) "
          f"from `eval/questions.jsonl` (sha256 `{ds['sha256'][:16]}...`).",
          f"- Every mode answers the same questions with the same version filters, the same corpus, "
          f"the same output depth (top-{meta['config']['top_k']}) in one process on one machine. "
          "Models are loaded once.",
          f"- Hybrid: BM25 top-{meta['config']['pool']} + dense top-{meta['config']['pool']} fused with "
          f"RRF (k={meta['config']['rrf_k']}). Rerank: the top {meta['config']['rerank_pool']} fused "
          f"candidates are rescored by `{meta['config']['reranker']}`.",
          f"- Dense model `{meta['config']['embedder']}`, search backend `{meta['config']['dense_backend']}`.",
          "- No ranking parameter, weight or ID boost was tuned on these questions; defaults were fixed "
          "before the benchmark was run.", ""]
    L += ["## 2. Dataset composition", ""]
    cat_rows = [[c, str(ds["by_category"].get(c, 0))] for c in CATEGORIES]
    L += _table(["Category", "Questions"], cat_rows)
    L += [f"Difficulty: {', '.join(f'{k} {v}' for k, v in sorted(ds['by_difficulty'].items()))}. "
          f"With a version filter: {ds['n_filtered']}; unfiltered: {ds['n_total'] - ds['n_filtered']}. "
          f"Relevant chunks per query: mean {ds['mean_relevant']:.2f} "
          f"(grade 2: {ds['n_grade2']}, grade 1: {ds['n_grade1']}).", ""]
    L += ["## 3. Relevance-label provenance", "",
          "- Labels were written by an AI assistant (Claude) by reading the stored source chunks and, for "
          "cross-version pairs, the official NIST crosswalk rows. **No retrieval output was used to "
          "choose or grade relevance.**",
          "- Chunk IDs, versions, pages, sections and source excerpts were checked against the SQLite "
          "database (`controlshift-db`); the test suite re-checks them.",
          "- **No human has reviewed these labels**; they must not be called independently verified. "
          "Audit them in `eval/questions_audit.md`.",
          f"- {ds['n_provisional']} query(ies) whose relevance is uncertain are marked `provisional` and "
          "excluded from every headline metric (reported separately in section 4b).",
          "- Chunks not listed as relevant are treated as non-relevant, so a retrieved chunk that is "
          "actually relevant but unlabelled lowers a score (a known bias, see section 10).", ""]
    L += ["## 4. Metric definitions", "",
          "- **Recall@k** = relevant chunks in the top k / all relevant chunks for the query.",
          "- **Hit@5** = 1 if at least one relevant chunk is in the top 5.",
          "- **MRR@10** = 1 / rank of the first relevant chunk within the top 10 (0 if none).",
          "- **nDCG@5** with gain 2^grade - 1 (grades 1 and 2), discount 1/log2(rank+1), normalised by the "
          "ideal ordering.",
          "- **Version isolation** (queries with a filter only) = share of queries whose returned "
          "results were all from the requested version.",
          "- Repeated chunk IDs count once at their first position. Scores are means over final "
          "queries; 95% CIs are seeded percentile bootstraps over queries.", ""]
    L += [f"### 4a. Overall results (n = {ds['n_final']} final queries)", ""]
    rows = []
    for m in names:
        o = modes[m]["overall"]
        rows.append([MODE_LABEL[m]] + [_f(o[k]) for k in HEADLINE])
    L += _table(["Mode"] + [FIELD[k] for k in HEADLINE], rows)
    rows = []
    for m in names:
        ci = modes[m]["ci95"]
        rows.append([MODE_LABEL[m]] + [f"{_f(modes[m]['overall'][k])} [{_f(ci[k][0])}, {_f(ci[k][1])}]"
                                       for k in ("ndcg@5", "mrr@10", "recall@5", "hit@5")])
    L += ["95% bootstrap confidence intervals:", ""]
    L += _table(["Mode", "nDCG@5", "MRR@10", "Recall@5", "Hit@5"], rows)
    if res.get("paired_vs_bm25"):
        L += ["Paired difference in nDCG@5 versus BM25 (mean, 95% bootstrap CI over queries):", ""]
        L += _table(["Mode", "Mean diff", "95% CI", "CI excludes 0?"], [
            [MODE_LABEL[m], f"{d['mean_diff']:+.3f}", f"[{d['ci95'][0]:+.3f}, {d['ci95'][1]:+.3f}]",
             "yes" if d["ci95"][0] > 0 or d["ci95"][1] < 0 else "no"]
            for m, d in res["paired_vs_bm25"].items()])
    L += ["### 4b. Version isolation and provisional queries", ""]
    rows = []
    for m in names:
        v = modes[m]["version_isolation"]
        p = modes[m]["provisional"]
        rows.append([MODE_LABEL[m], str(v["queries_with_filter"]),
                     _f(v["accuracy_all_results_in_version"]), _f(v["mean_fraction_in_version"]),
                     _f(p["ndcg@5"]) if p else "-", _f(p["recall@10"]) if p else "-"])
    L += _table(["Mode", "Filtered queries", "Isolation accuracy", "Mean in-version share",
                 "Provisional nDCG@5", "Provisional Recall@10"], rows)
    L += ["Version isolation is expected to be 1.0 by construction (the filter is applied inside each "
          "retriever); the check guards against regressions.", ""]
    L += ["## 5. Per-category performance", ""]
    for metric in ("ndcg@5", "mrr@10", "recall@5"):
        L += [f"**{FIELD[metric]}**", ""]
        rows = []
        for c in CATEGORIES:
            if c in modes[names[0]]["by_category"]:
                rows.append([c, str(modes[names[0]]["by_category"][c]["n"])] + [
                    _f(modes[m]["by_category"][c][metric]) for m in names])
        L += _table(["Category", "n"] + [MODE_LABEL[m] for m in names], rows)
    L += ["With so few queries per category, differences of a few hundredths are not meaningful.", ""]
    L += ["## 6. Latency", ""]
    cold, lat = res["cold_start"], res["latency"]
    L += ["Cold initialisation (separate from query latency, measured once in this process):", ""]
    order = [k for k in COLD_ORDER if k in cold] + sorted(k for k in cold if k not in COLD_ORDER)
    L += _table(["Step", "Seconds"], [[k, _f(cold[k], 2)] for k in order])
    L += [f"Warm per-query latency (single process; {lat['config']['reps']} timed passes x "
          f"{ds['n_total']} queries after {lat['config']['warmup_passes']} warm-up pass(es); "
          "ms, top-10, includes everything from query text to ranked hits):", ""]
    L += _table(["Mode", "Mean", "p50", "p95", "Min", "Max", "Samples"], [
        [MODE_LABEL[m]] + [_f(lat["modes"][m][k], 1) for k in
                           ("mean_ms", "p50_ms", "p95_ms", "min_ms", "max_ms")]
        + [str(lat["modes"][m]["n"])] for m in names])
    if lat.get("stages"):
        L += ["Hybrid pipeline stages (ms, same warm protocol; stages run separately so they do not sum "
              "exactly to the end-to-end rows):", ""]
        L += _table(["Stage", "Mean", "p50", "p95"], [
            [s] + [_f(v[k], 1) for k in ("mean_ms", "p50_ms", "p95_ms")]
            for s, v in sorted(lat["stages"].items(), key=lambda kv: (
                STAGE_ORDER.index(kv[0]) if kv[0] in STAGE_ORDER else len(STAGE_ORDER), kv[0]))])
    L += ["Timings are for this machine only and vary between runs; they are not reproducible to "
          "the digit, unlike the quality metrics.", ""]
    ex = res.get("examples")
    if ex:
        L += ["## 7. Where hybrid RRF helps", "",
              "Definition: hybrid nDCG@5 is strictly higher than the better of BM25 and dense for the "
              "same query. Ranks are the position of the first relevant chunk.", ""]
        L += _examples("Hybrid better than both components", ex["hybrid_helps"])
        L += ["## 8. Where hybrid RRF performs worse", "",
              "Definition: hybrid nDCG@5 is strictly lower than the better of BM25 and dense.", ""]
        L += _examples("Hybrid worse than the best single retriever", ex["hybrid_hurts"])
        L += ["### Reranker versus plain hybrid", ""]
        L += _examples("Reranker improves nDCG@5", ex["rerank_helps"], 6)
        L += _examples("Reranker lowers nDCG@5", ex["rerank_hurts"], 6)
    L += ["## 9. Summary of measured differences", ""]
    best = max(names, key=lambda m: modes[m]["overall"]["ndcg@5"])
    L += [f"- Highest overall nDCG@5 in this run: **{MODE_LABEL[best]}** "
          f"({_f(modes[best]['overall']['ndcg@5'])}). This is a point estimate on "
          f"{ds['n_final']} queries; check the confidence intervals above before concluding that "
          "modes differ.", ""]
    L += ["## 10. Known limitations and threats to validity", "",
          f"- **Small sample**: {ds['n_final']} final queries; per-category cells have 8-11 queries. "
          "Confidence intervals are wide.",
          "- **Labels are AI-curated and not human-reviewed**; some judgments (grade 1 vs not relevant) "
          "are subjective, and the author of the labels is a language model with possible blind spots.",
          "- **Incomplete labels**: unlabelled chunks count as non-relevant, so correct-but-unlabelled "
          "retrievals (e.g. a neighbouring subcategory) are penalised. This affects all modes but not "
          "equally.",
          "- **Corpus-specific**: CSF is a small, highly structured corpus (384 chunks); results do not "
          "generalise to large corpora or other domains.",
          "- **Question style**: questions were written for this benchmark by the same assistant that "
          "built the system's tests; many control-level queries are close paraphrases of control "
          "text, which favours lexical overlap.",
          "- **Exact-ID and tie behaviour** of RRF (equal weights, deterministic chunk-ID tie-break) "
          "was not tuned; any ID-aware boosting is future work that must be evaluated on a separate "
          "held-out set to avoid overfitting to these questions.",
          "- **Latency** is measured on one machine, single-threaded request loop, warm caches; not a "
          "load test. Results depend on the device PyTorch selected (see environment).",
          "- Dense passages are scored as parent chunks; sub-passage retrieval quality is not "
          "measured separately.", ""]
    L += ["## 11. Environment", "", "```json"]
    import json
    L += [json.dumps({k: meta[k] for k in ("hardware", "libraries", "config", "devices", "git_commit",
                                           "corpus", "generated_utc") if k in meta}, indent=2,
                     sort_keys=True), "```", ""]
    return "\n".join(L)


__all__ = ["METRIC_NAMES", "render_report"]
