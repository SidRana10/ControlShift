"""Markdown report and human-review worksheet for the grounded-answer evaluation."""
from __future__ import annotations

from .answers import CATEGORIES, COMPLETENESS, GROUNDEDNESS, review_summary


def _pct(x) -> str:
    return "-" if x is None else f"{100 * x:.0f}%"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    return (["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
            + ["| " + " | ".join(r) + " |" for r in rows] + [""])


def render_answer_report(res: dict, reviews: dict) -> str:
    meta, ev, st = res["meta"], res["evidence_stage"], res["validator_self_test"]
    agg = ev["aggregate"]
    L = ["# Grounded-answer evaluation (offline)", "",
         "_Generated by `eval/answer_eval.py` from `eval/answer_results.json`. **No language model was "
         "called to produce any number below.** Gold labels are AI-curated and source-checked, **not "
         "human-reviewed**._", ""]
    L += ["## 1. What this evaluates, and what it does not", "",
          "Three assurance levels are kept separate:", "",
          "| Level | Question answered | Who decides |", "|---|---|---|",
          "| Structural | Do cited chunk / crosswalk-row ids exist, belong to the evidence bundle and match stored provenance? | code |",
          "| Deterministic factual | Do mappings equal official crosswalk rows? Are versions right? Are conflicts preserved? Is abstention right? Is removal wording supported? | code, against SQLite + gold |",
          "| Semantic faithfulness | Is the prose actually supported by the cited text? Is it complete and clear? | **a human reviewer (pending)** |", "",
          "Passing structural and deterministic checks does **not** show that an answer is faithful. "
          "Offline mode measures (a) the evidence the pipeline hands to a model and (b) whether the "
          "checker itself works. It says nothing about Gemini's accuracy.", ""]
    L += ["## 2. Gold dataset", "",
          f"- {meta['n_questions']} questions from `eval/answer_questions.jsonl` (sha256 `{meta['gold_sha256'][:16]}...`).",
          "- Expectations come from the stored NIST text and official crosswalk rows: quoted facts are verified as "
          "substrings of stored chunks, crosswalk row sets are read from SQLite, conflict/new/unmapped claims are "
          "re-verified against the rows, and 'absent' topics are verified to occur nowhere in the corpus.",
          "- **Not human-reviewed** (`human_reviewed: false` on every record). No generated answer was used as ground truth.",
          "- `abstention` = a valid question whose evidence cannot support an answer (unknown control; topic absent from "
          "the corpus, justified by several concept terms having zero occurrences rather than one missing keyword). "
          "`invalid_input` = a blank/invalid request: the API returns HTTP 422 before any retrieval or generation, so it is "
          "not an abstention and is never sent to a model.", ""]
    L += _table(["Category", "Questions"], [[c, str(meta["by_category"].get(c, 0))] for c in CATEGORIES])
    L += ["## 3. Evidence-pipeline checks (deterministic regression validation, no LLM)", "",
          "**This is regression validation of the deterministic pipeline - not live-model answer accuracy.** "
          "A high pass rate means the pipeline still assembles the evidence the gold file expects; it says "
          "nothing about what any model will write.", "",
          f"Evidence is assembled with `{meta['retrieval']}` retrieval (no models needed). A question passes if no "
          f"applicable check fails. **{agg['questions_all_checks_passed']} of {agg['n_questions']} questions "
          "passed every applicable check.**", ""]
    L += _table(["Check", "Applicable", "Passed", "Failed", "Pass rate"], [
        [n, str(v["applicable"]), str(v["passed"]), str(v["failed"]), _pct(v["pass_rate"])]
        for n, v in agg["per_check"].items()])
    L += _table(["Category", "Questions", "All checks passed"], [
        [c, str(v["questions"]), str(v["all_passed"])] for c, v in agg["per_category"].items()])
    fails = [(q, c) for q, r in ev["per_question"].items() for c in r["checks"] if c["status"] == "fail"]
    L += ["### Failures", ""]
    if fails:
        L += _table(["Question", "Check", "Detail"], [[q, c["name"], c["detail"].replace("|", "/")[:160]]
                                                     for q, c in fails])
        L += ["These are real shortcomings of the evidence stage under this retrieval mode, reported as "
              "measured; nothing was tuned to remove them.", ""]
    else:
        L += ["_none_", ""]
    L += ["## 4. Validator self-test (synthetic fixtures)", "",
          f"{st['scope']}. {st['fixtures_accepted']} of {st['fixtures_built']} gold-derived reference answers "
          "were accepted by the checker. Each defect type below was injected into every applicable accepted "
          "fixture; 'detected' means the specific check failed.", ""]
    if st["fixture_failures"]:
        L += [f"Reference fixtures rejected: {st['fixture_failures']}", ""]
    L += _table(["Injected defect", "Applicable fixtures", "Detected", "Missed"], [
        [n, str(v["applicable"]), str(v["detected"]), ", ".join(v["missed"]) or "-"]
        for n, v in st["corruptions"].items()])
    L += ["Detection of synthetic defects shows the checks fire as designed; it is not evidence about real "
          "model outputs, whose errors may look different.", ""]
    rs = review_summary(reviews)
    L += ["## 5. Human review status", "",
          f"- Reviewed: {rs['reviewed']} / {rs['total']}; pending: {rs['pending']}.",
          "- Groundedness and completeness are **unscored** until a reviewer fills in "
          "`eval/answer_review.json` (see `eval/answer_review_worksheet.md`).", ""]
    live = res.get("live")
    L += ["## 6. Live-provider mode", "",
          ("A live run is included: " + f"provider `{live['provider']}`, model `{live['model']}`, "
           f"{live['questions_run']} question(s), is_live_model={live['is_live_model']}.")
          if live else "Not run. Live mode is disabled by default; it needs `--live`, `RUN_LIVE_LLM_EVAL=1` and "
          "Gemini credentials, makes at most `--live-limit` requests and never retries a failed generation. "
          "No live answer accuracy is reported here.", ""]
    L += ["## 7. Limitations", "",
          "- 20 questions; one gold author (an AI); no human review of labels or answers.",
          "- Evidence-stage results depend on the BM25 retrieval used here; hybrid/rerank evidence may differ. "
          "The gold file was written by the same assistant that built the pipeline, so high pass rates are "
          "regression checks, not evidence of robustness on unseen questions.",
          "- The removal-wording rule is a keyword heuristic; synonyms are missed and benign uses can be flagged.",
          "- Conflict and mapping checks verify structure (ids, rows, pairs), not whether the prose describes them well.",
          "- The self-test uses defects we thought of; real model failure modes may be missed.", ""]
    return "\n".join(L)


def render_worksheet(gold: list[dict], res: dict, reviews: dict, generated: dict | None = None) -> str:
    """One block per question for a human reviewer. Subjective fields stay PENDING until filled."""
    L = ["# Answer review worksheet", "",
         "Reviewer instructions: for each question read the expected facts and the cited evidence, then edit "
         "`eval/answer_review.json` (not this file). `groundedness` ∈ "
         f"{GROUNDEDNESS}; `completeness` ∈ {COMPLETENESS}; set `status` to `reviewed` and add your name. "
         "Leave `pending` if you have not examined the answer. **All scores are currently pending.**", ""]
    ev = res["evidence_stage"]["per_question"]
    for g in gold:
        q = g["question_id"]
        r = reviews[q]
        L += [f"## {q} - {g['question'].strip() or '(blank question)'}", "",
              f"- Category: `{g['category']}`  |  Expected query type: `{g['expected_query_type']}`  |  "
              f"Allowed versions: {', '.join(g['allowed_versions'])}",
              "- Labels: AI-curated, source-checked, **not human-reviewed**"]
        if g["must_abstain"]:
            L += [f"- **Should abstain** ({g['abstention_basis']}): {g['abstention_conditions']}"]
            if g.get("abstention_justification"):
                L += [f"- Why abstention is justified: {g['abstention_justification']}"]
        if g.get("invalid_input"):
            L += [f"- **Invalid input**: the API must reject this with HTTP {g['expected_api_status']} "
                  f"(no retrieval, no model call). {g['abstention_conditions']}"]
        L += ["", "**Expected evidence and facts**", ""]
        for c in g["expected_controls"]:
            L += [f"- control `{c['control_id']}` (CSF {c['version']})"]
        for f in g["expected_facts"]:
            quote = f" - \"{f['quote']}\"" if f["type"] == "text" else ""
            L += [f"- fact: {f['statement']} [{f['evidence']}]{quote}"]
        if g["conflict_rows"]:
            L += [f"- must preserve conflicting rows {g['conflict_rows']} (do not choose one)"]
        if g["forbidden_mapping_controls"]:
            L += [f"- must NOT claim a mapping or removal for {g['forbidden_mapping_controls']}"]
        e = ev[q]["bundle_summary"]
        L += ["", "**Evidence the pipeline assembled (offline)**", "",
              f"- query type `{e['query_type']}`; searched {e['searched_versions']}; controls {e['controls']}; "
              f"crosswalk rows {e['crosswalk_rows']}; passages {e['n_passages']}; conflicts {e['conflicts']}; "
              f"unmapped {e['unmapped']}; missing {e['missing_evidence']}",
              "- evidence checks: " + (", ".join(f"{c['name']}={c['status']}" for c in ev[q]["checks"])), ""]
        L += ["**Generated answer**", ""]
        gen = (generated or {}).get(q)
        if gen and gen.get("answer"):
            a = gen["answer"]
            L += [a["answer"].strip() or "_(abstained)_", "",
                  f"- citations: {a['citations']}",
                  f"- mappings: {[(m['focal_id'], m['reference_id'], m['citations']) for m in a['mappings']]}",
                  "- deterministic checks: " + ", ".join(f"{c['name']}={c['status']}" for c in gen["checks"])]
        else:
            L += ["_Not generated - offline mode (no model was called)._"]
        L += ["", "**Review**", "",
              f"- Groundedness: {(r['groundedness'] or 'PENDING').upper() if r['groundedness'] else 'PENDING'}",
              f"- Completeness: {(r['completeness'] or 'PENDING').upper() if r['completeness'] else 'PENDING'}",
              f"- Reviewer notes: {r['notes'] or '_(blank)_'}",
              f"- Reviewer: {r['reviewer'] or '_(none)_'}",
              f"- Human review status: **{r['status']}**", ""]
    return "\n".join(L)
