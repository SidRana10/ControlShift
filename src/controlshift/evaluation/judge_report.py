"""Report and calibration worksheet for the judged evaluation. Four kinds of result are kept in
separate sections and a section is only filled from data of the matching kind:
  offline fixtures | real generator (deterministic checks) | LLM judge | human-reviewed."""
from __future__ import annotations

from .judge import DIMENSIONS, RUBRIC, RUBRIC_VERSION, numeric_scores


def _f(x, nd=2):
    return "-" if x is None else f"{x:.{nd}f}"


def _table(header, rows):
    return (["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
            + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows] + [""])


MODE_LABEL = {"bm25": "BM25", "dense": "Dense", "hybrid": "Hybrid RRF", "hybrid_rerank": "Hybrid RRF + cross-encoder"}


def render_judge_report(retrieval: dict | None, offline: dict | None, live: dict | None,
                        calibration: dict | None, agreement: dict | None) -> str:
    real = bool(live) and live.get("kind") == "real_generator"
    judged_live = real and live.get("judge_kind") == "live_llm_judge"
    L = ["# ControlShift quality evaluation", "",
         "_Generated by `eval/judge_eval.py`. Every number comes from a stored results file; nothing is estimated "
         "or typed by hand. Labels are AI-curated and source-checked, **not human-reviewed**._", "",
         "## 0. Result types (kept separate)", ""]
    L += _table(["Result type", "What it is", "Present in this report"], [
        ["Offline fixture", "Deterministic checks of the evidence pipeline and of the validator on synthetic data; no model", "yes" if offline else "no"],
        ["Real generator", "Gemini-generated answers checked by the deterministic validators", "yes" if real else "no (not run)"],
        ["LLM judge", "A judge model's 1-5 scores and claim verdicts; an opinion, not ground truth", "yes" if judged_live else "no (not run)"],
        ["Human-reviewed", "Scores entered by a human reviewer; judge/human agreement", "yes" if agreement and agreement["reviewed_and_judged"] else "no (none reviewed)"]])
    L += ["## 1. Retrieval effectiveness (offline benchmark)", ""]
    if retrieval:
        ds = retrieval["meta"]["dataset"]
        L += [f"{ds['n_final']} final queries (labels AI-curated, not human-reviewed), top-10, same questions and filters for every mode.", ""]
        rows = []
        for m, label in MODE_LABEL.items():
            if m in retrieval["modes"]:
                o, lat = retrieval["modes"][m]["overall"], retrieval["latency"]["modes"][m]
                rows.append([label, _f(o["recall@5"], 3), _f(o["mrr@10"], 3), _f(o["ndcg@5"], 3),
                             _f(o["hit@5"], 3), _f(lat["p50_ms"], 1), _f(lat["p95_ms"], 1)])
        L += _table(["Mode", "Recall@5", "MRR@10", "nDCG@5", "Hit@5", "p50 ms", "p95 ms"], rows)
        L += ["See `eval/report.md` for confidence intervals, per-category tables and limitations.", ""]
    else:
        L += ["_`eval/results.json` not available._", ""]
    L += ["## 2. Offline fixture results (regression validation, not model accuracy)", ""]
    if offline:
        agg, st = offline["evidence_stage"]["aggregate"], offline["validator_self_test"]
        L += [f"- Evidence stage: {agg['questions_all_checks_passed']} of {agg['n_questions']} questions passed every applicable check.",
              f"- Validator self-test: {st['fixtures_accepted']} of {st['fixtures_built']} reference answers accepted; "
              f"{sum(v['detected'] for v in st['corruptions'].values())} of "
              f"{sum(v['applicable'] for v in st['corruptions'].values())} injected defects detected.",
              "- These describe the deterministic pipeline and checker. No language model produced any of it.", ""]
    else:
        L += ["_`eval/answer_results.json` not available._", ""]
    L += ["## 3. Real generator results (deterministic checks only)", ""]
    if not live:
        L += ["**Not run.** Run `eval/judge_eval.py --live` (see PROGRESS.md for the exact command).", ""]
    elif not real:
        L += [f"The supplied run used a mocked or missing generator (`{live['generator']}`); it only tests the plumbing and "
              "is deliberately not reported as a result.", ""]
    else:
        n_req, b = len(live["questions_requested"]), live["budgets"]
        L += [f"- Generator: `{live['generator']['name']}` / `{live['generator']['model']}`; run status: **{live['status']}**"
              + (f" ({live['stopped_reason']})" if live["stopped_reason"] else ""),
              f"- Questions requested: {n_req}; generation requests made: {b['generation_requests_made']} "
              f"(budget {b['max_generation_requests']}); automatic retries: none.",
              "- **Sample size warning: this is a small smoke evaluation, not a statistically meaningful accuracy benchmark.**", ""]
        rows = []
        for q, r in live["per_question"].items():
            d = r.get("deterministic")
            rows.append([q, r["category"], r["generation"]["status"],
                         "-" if not d else ("all passed" if d["all_passed"] else "FAILED: " + ", ".join(
                             c["name"] for c in d["checks"] if c["status"] == "fail"))])
        L += _table(["Question", "Category", "Generation status", "Deterministic checks"], rows)
        da = live.get("deterministic_aggregate")
        if da:
            focus = ["schema_valid", "citation_ids_valid", "citations_in_bundle", "mapping_pairs_official",
                     "mapping_cites_matching_row", "expected_rows_covered", "versions_correct", "conflict_preserved",
                     "new_control_no_reference", "no_forbidden_mappings", "no_unsupported_removal", "abstention_correct"]
            L += ["Per-check results over attempted questions (n/a excluded):", ""]
            L += _table(["Check", "Applicable", "Passed", "Failed"], [
                [c, da["per_check"][c]["applicable"], da["per_check"][c]["passed"], da["per_check"][c]["failed"]]
                for c in focus if c in da["per_check"]])
        lat = live["latency"]
        L += ["End-to-end latency (seconds; evidence assembly + generation [+ judging]):", ""]
        L += _table(["Stage", "n", "Mean", "Median", "Max"], [
            [k, v["n"], _f(v.get("mean_s")), _f(v.get("median_s")), _f(v.get("max_s"))] for k, v in lat.items()])
    L += ["## 4. LLM judge results (an opinion, not ground truth)", ""]
    if not judged_live:
        L += ["**Not run.** No live judge scores exist; none are shown.", ""]
    else:
        ja = live["judge_aggregate"]
        L += [f"- Judge: `{live['judge']['name']}` / `{live['judge']['model']}`; rubric version {live['rubric_version']}.",
              f"- **Independence:** {live['independence_note']}",
              f"- Judged answers: {ja['judged']} of {ja['questions']} (status counts: {ja['status_counts']}). Missing judgments "
              "(abstentions, invalid output, provider errors) are not imputed.", ""]
        L += _table(["Dimension", "n", "Mean (1-5)", "Distribution"], [
            [d, ja["dimensions"][d]["n"], _f(ja["dimensions"][d]["mean"]), ja["dimensions"][d]["distribution"]] for d in DIMENSIONS])
        c, u = ja["claims"], ja["units"]
        L += [f"Faithfulness is computed per answer unit against the retrieved evidence only: {u['supported']} supported / "
              f"{u['unsupported']} unsupported / {u['unclear']} unclear of {u['factual_units']} factual units (supported rate "
              f"{_f(u['supported_rate'])}). The judge had to account for every unit, so omitted claims cannot raise the score. "
              f"Claim-level counts: {c['supported']} / {c['unsupported']} / {c['unclear']} of {c['total']}. "
              f"Citation verdicts: {ja['citation_verdicts']}.",
              "Dimensions that did not apply to a judged answer (e.g. faithfulness with no factual units, citation support with no "
              f"citations) are excluded from the means, not scored: {ja['not_applicable']}.", ""]
        rows = []
        for q, r in live["per_question"].items():
            j = r.get("judgment")
            if j and j["status"] == "judged":
                s = numeric_scores(j["derived"])
                rows.append([q] + [s[d] if s[d] is not None else "n/a" for d in DIMENSIONS])
            else:
                rows.append([q] + [(j["status"] if j else "-")] + ["-"] * (len(DIMENSIONS) - 1))
        L += _table(["Question", *DIMENSIONS], rows)
    L += ["## 5. Human-reviewed results and judge/human agreement", ""]
    pend = sum(1 for v in (calibration or {}).values() if v["status"] == "pending")
    rev = sum(1 for v in (calibration or {}).values() if v["status"] == "reviewed")
    L += [f"Calibration entries: {rev} reviewed, {pend} pending (`eval/judge_calibration.json`)."]
    if agreement and agreement["reviewed_and_judged"]:
        L += [f"Questions both judged and human-reviewed: {agreement['reviewed_and_judged']}. Descriptive only at this sample size.", ""]
        L += _table(["Dimension", "n", "Exact", "Within 1", "Mean abs diff", "Judge - human"], [
            [d, v["n"], _f(v.get("exact_agreement")), _f(v.get("within_one")), _f(v.get("mean_abs_diff")),
             _f(v.get("judge_minus_human_mean"))] for d, v in agreement["per_dimension"].items()])
        if agreement["disagreements_ge_2_points"]:
            L += ["Disagreements of 2+ points: " + ", ".join(
                f"{g['question_id']}/{g['dimension']} (judge {g['judge']}, human {g['human']})"
                for g in agreement["disagreements_ge_2_points"]), ""]
    else:
        L += ["No question has been both judged by a real judge and reviewed by a human, so **no agreement figure exists**.", ""]
    L += ["## 6. Rubric", "", f"Rubric version {RUBRIC_VERSION}. Faithfulness is derived from claim verdicts: " + RUBRIC["faithfulness"], ""]
    for d in ("answer_relevance", "factual_correctness", "completeness", "citation_support"):
        L += [f"**{d}**", ""] + [f"- {k}: {v}" for k, v in sorted(RUBRIC[d].items(), reverse=True)] + [""]
    L += ["## 7. Limitations", "",
          "- A judge model can be wrong, inconsistent and biased toward its own style; it is calibrated, not trusted.",
          "- Using the same model (or vendor family) as generator and judge does not give an independent evaluation.",
          "- Deterministic validators remain authoritative for mappings, versions, conflicts, citation structure and abstention; the judge adds prose-level opinions only.",
          "- Gold facts and retrieval labels are AI-curated and not human-reviewed.",
          "- Small samples (6 or 19 questions) cannot support accuracy claims.", ""]
    return "\n".join(L)


def render_judge_worksheet(questions: list[dict], live: dict | None, calibration: dict, conn) -> str:
    """Per question: gold facts, Gemini answer, source evidence, deterministic results, judge scores and
    PENDING human fields (including a judge/human disagreement note)."""
    L = ["# Judge calibration worksheet", "",
         "Edit `eval/judge_calibration.json` (not this file): set `status` to `reviewed`, add your name, give each of the five dimensions an "
         "integer 1-5 using the rubric in `eval/judge_report.md`, and record any disagreement with the LLM judge in `disagreement_notes`. "
         "**All human fields are currently pending unless shown otherwise.**", ""]
    for g in questions:
        q = g["question_id"]
        rec = (live or {}).get("per_question", {}).get(q)
        c = calibration[q]
        L += [f"## {q} - {g['question']}", "", f"- Category: `{g['category']}`; labels AI-curated, **not human-reviewed**", "",
              "**Gold expected facts**", ""]
        L += [f"- {f['statement']} [{f['evidence']}]" + (f" - \"{f['quote']}\"" if f.get("quote") else "") for f in g["expected_facts"]]
        if g["conflict_rows"]:
            L += [f"- must preserve conflicting rows {g['conflict_rows']}"]
        if g["must_abstain"]:
            L += [f"- should abstain: {g['abstention_conditions']}"]
        L += ["", "**Gemini answer**", ""]
        gen = rec["generation"] if rec else None
        ans = gen.get("answer") if gen else None
        if ans:
            L += [ans["answer"].strip(), "", f"- citations: {ans['citations']}",
                  f"- mappings: {[(m['focal_id'], m['reference_id'], m['citations']) for m in ans['mappings']]}"]
        elif gen and gen["status"] == "abstained":
            L += [f"_Abstained: {gen.get('abstention_reason')}_"]
        else:
            L += ["_Not generated (no live run)._" if not gen else f"_No answer ({gen['status']})._"]
        L += ["", "**Source evidence cited**", ""]
        for cid in (ans["citations"] if ans else []):
            text = None
            if cid.startswith("chunk:"):
                r = conn.execute("SELECT text FROM chunk WHERE chunk_id=?", (cid[6:],)).fetchone()
                text = r[0] if r else None
            elif cid.startswith("xwalk:row"):
                r = conn.execute("SELECT focal_original_id||' -> '||coalesce(reference_original_id,'(none)')||' ['||mapping_type||'] '||"
                                 "coalesce(comments,'') FROM crosswalk_mapping WHERE excel_row=?", (int(cid[9:]),)).fetchone()
                text = r[0] if r else None
            L += [f"- `{cid}`: {(text or '(missing)')[:300].replace(chr(10), ' ')}"]
        if not ans:
            L += ["_none_"]
        L += ["", "**Deterministic results**", ""]
        d = rec.get("deterministic") if rec else None
        L += [", ".join(f"{x['name']}={x['status']}" for x in d["checks"]) if d else "_not run_", "",
              "**LLM judge**", ""]
        j = rec.get("judgment") if rec else None
        if j and j["status"] == "judged":
            s = numeric_scores(j["derived"])
            L += ["- scores (1-5): " + ", ".join(f"{k}={'n/a' if v is None else v}" for k, v in s.items()),
                  f"- judge: {j['judge'].get('name')}/{j['judge'].get('model')}; independence: "
                  f"{(live or {}).get('independence_note', 'unknown')}",
                  f"- faithfulness units: {j['derived']['faithfulness']['unit_verdicts']} "
                  f"(non-factual: {j['derived']['faithfulness']['non_factual_units']})", "",
                  "| Claim | Units | Evidence | Verdict | Justification |", "|---|---|---|---|---|"]
            L += [f"| {cl['claim'][:80]} | {', '.join(cl['unit_ids'])} | {', '.join(cl['evidence_ids'])} | {cl['verdict']} | "
                  f"{cl['justification'][:80]} |" for cl in j["output"]["claims"]]
        else:
            L += [f"_{'not run' if not j else j['status'] + ': ' + (j.get('reason') or '')}_"]
        L += ["", "**Human review**", "", f"- Status: **{c['status']}**; reviewer: {c['reviewer'] or '_(none)_'}"]
        L += [f"- {d_}: {c['human_scores'][d_] if c['human_scores'][d_] is not None else 'PENDING'}" for d_ in DIMENSIONS]
        L += [f"- Judge/human disagreement notes: {c['disagreement_notes'] or '_(blank)_'}",
              f"- Reviewer notes: {c['notes'] or '_(blank)_'}", ""]
    return "\n".join(L)
